TABLES = {"nl_NL": NL, "es_ES": ES, "ja_JP": JA}


def parse_pot(path):
    """Return [(references, msgid)] in template order, ignoring the header."""
    text = path.read_text(encoding="utf-8")
    entries = []
    for block in text.split("\n\n"):
        lines = [ln for ln in block.split("\n") if ln.strip()]
        refs = [ln for ln in lines if ln.startswith("#:")]
        if not lines:
            continue
        ids = []
        cur = None
        for ln in lines:
            if ln.startswith("msgid"):
                cur = "id"
                ids = [ln[ln.index('"') + 1:-1]] if '"' in ln else []
            elif ln.startswith("msgstr"):
                cur = "str"
            elif ln.startswith('"') and cur == "id":
                ids.append(ln[1:-1])
            elif ln.startswith('"') and cur == "str":
                continue
            else:
                cur = None
        msgid = "".join(ids)
        if msgid:
            entries.append((refs, msgid))
    return entries


def quote(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def write_po(locale, entries, table):
    title, lang, plural = HEADERS[locale]
    missing = []
    out = ["# %s" % title,
           "# Copyright (C) 2026 Josep Bigorra <jjbigorra@gmail.com>",
           "# This file is distributed under the same license as the lucidplan package.",
           "#",
           'msgid ""',
           'msgstr ""',
           '"Project-Id-Version: lucidplan\\n"',
           '"Report-Msgid-Bugs-To: \\n"',
           '"PO-Revision-Date: 2026-10-12 20:00+0100\\n"',
           '"Last-Translator: Automatically generated\\n"',
           '"Language-Team: none\\n"',
           '"Language: %s\\n"' % lang,
           '"MIME-Version: 1.0\\n"',
           '"Content-Type: text/plain; charset=UTF-8\\n"',
           '"Content-Transfer-Encoding: 8bit\\n"',
           '"%s"' % plural,
           ""]
    for refs, msgid in entries:
        target = msgid if locale == "en_US" else table.get(msgid, "")
        if locale != "en_US" and not target:
            missing.append(msgid)
        out.extend(refs)
        out.append("msgid %s" % quote(msgid))
        out.append("msgstr %s" % quote(target))
        out.append("")
    path = LOCALE_DIR / locale / "LC_MESSAGES" / "translate.po"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(out), encoding="utf-8")
    return path, missing


def main():
    entries = parse_pot(POT)
    print("template entries: %d" % len(entries))
    failed = False
    for locale in ("en_US", "nl_NL", "es_ES", "ja_JP"):
        path, missing = write_po(locale, entries, TABLES.get(locale, {}))
        if missing:
            print("  %s: no translation for %d: %s"
                  % (locale, len(missing), "; ".join(missing[:6])))
        mo = path.with_suffix(".mo")
        result = subprocess.run(["msgfmt", "-c", "-o", str(mo), str(path)],
                                capture_output=True, text=True)
        status = "ok" if result.returncode == 0 else "FAILED"
        print("  %s: %s (%s)" % (locale, status, result.stderr.strip() or "no diagnostics"))
        if result.returncode != 0:
            failed = True
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
